# Valid eye-tracking statistics
.valid_et_stats <- c(
  "fixation_count",
  "dwell_time_total",
  "dwell_time_mean",
  "dwell_time_median",
  "dwell_time_sd",
  "switches_direct",
  "switches_total",
  "revisits_count",
  "transitions_ref_to_ref",
  "direct_transitions_ref_to_ref",
  "direct_transitions_query_refs",
  "transitions_query_ref1",
  "direct_transitions_query_ref1",
  "transitions_query_ref2",
  "direct_transitions_query_ref2",
  "first_fixation_start",
  "first_reference_fixation_start",
  "first_fixated_aoi",
  "first_fixated_reference",
  "last_fixation_end",
  "last_reference_fixation_end",
  "last_fixated_aoi",
  "last_fixated_reference",
  "watch_time"
)

# Transition statistics that require `query_aoi` and `reference_aois`
.transitions_et_stats <- c(
  "transitions_ref_to_ref",
  "transitions_query_refs",
  "transitions_query_ref1",
  "transitions_query_ref2"
)

# Reference-related statistics that require `reference_aois`
.reference_et_stats <- c(
  "first_reference_fixation_start",
  "first_fixated_reference",
  "last_reference_fixation_end",
  "last_fixated_reference"
)

# Structural fills for eye tracking statistics
.et_measure_fills <- list(
  fixation_count         = 0L,
  revisits_count         = 0L,
  switches_total         = 0L,
  transitions_ref_to_ref = 0L,
  transitions_query_refs = 0L,
  transitions_query_ref1 = 0L,
  transitions_query_ref2 = 0L,
  dwell_time_total       = 0
)


#' Compute trial-level grouped eye-tracking measures
#'
#' Using export from EyeLink eye-tracking experiment in Experimental Builder,
#' such as data generated by \code{import_eyelink_group}, the function extracts
#' selected eye-tracking statistics per user-specified groups of observations.
#'
#' @param x An `mpr_eyelink_eyetracking` object.
#' @param trial_vars Character vector of variables denoting a unique trial
#'   identification. These variables need to be present in both `x$fixations`
#'   and `x$responses`
#' @param grp_vars Character vector of grouping variable names, or `NULL`.
#'   The analysis is not stratified by `grp_vars` in this step, bacause only
#'   grouping variables that would alter results would need to be intra-trial.
#'   Instead, the function assumes each trial must fall within a single group,
#'   and `grp_vars` are saved as an attribute and kept in data for future use.
#' @param stats Character vector of statistics to compute; validated against
#'   `.valid_et_stats`.
#' @param window Numeric. Upper bound on fixation `etime`; `Inf` keeps all.
#' @param query_aoi Character(1). Label of the query AOI, or `NULL`. Required
#'   only for `transitions_*` statistics.
#' @param reference_aois Character(2) labels of the reference AOIs, or `NULL`.
#'   Required for `transitions_*` and `*_reference_*` statistics .
#'
#' @returns A data.frame with one row per identifier x `trial_vars` x `grp_vars`
#'   x `aoi` combination and one column per requested statistic. Carries
#'   `id_cols`, `trial_cols`, and `grp_vars` as attributes so that
#'   later computation and plotting can average over correct levels withou the
#'   need to re-supply them.
#'
#' @noRd
.process_et_measures <- function(
    x,
    trial_vars,
    grp_vars,
    stats,
    window,
    query_aoi,
    reference_aois
) {
  # --- Validate requested statistics ------------------------------------------
  unknown_stats <- setdiff(stats, c(.valid_et_stats, "all"))
  if (length(unknown_stats) > 0L) {
    cli::cli_abort(c(
            "Unknown statistic{?s} requested in `stats`: {.val {unknown_stats}}.",
      "i" = "Valid statistics are: {.val {(.valid_et_stats)}}."
    ))
  }

  requested_transitions <- intersect(stats, .transitions_et_stats)
  if (length(requested_transitions) > 0L) {
    if (is.null(query_aoi) || is.null(reference_aois)) {
      cli::cli_abort(c(
              "Transition statistics require both `query_aoi` and `reference_aois`.",
        "x" = "Requested transition stat{?s}: {.val {requested_transitions}}.",
        "i" = "Supply the `query_aoi` and both `reference_aois`."
      ))
    }
    if (!all(c(query_aoi, reference_aois) %in% x$layout$aoi)) {
      cli::cli_abort(c(
              "`query_aoi` and both `reference_aois` must be present in `x$layout$aoi`.",
        "i" = "Supplied `query_aoi`: {.val {query_aoi}}.",
        "i" = "Supplied `reference_aois`: {.val {reference_aois}}.",
        "i" = "Supplied `x$layout$aoi`: {.val {x$layout$aoi}}."
      ))
    }
  }

  requested_reference_stats <- intersect(stats, .reference_et_stats)
  if (length(requested_reference_stats) > 0L) {
    if (is.null(reference_aois)) {
      cli::cli_abort(c(
              "Reference image-related statistics require `reference_aois`.",
        "x" = "Requested reference-related stat{?s}: {.val {requested_reference_stats}}.",
        "i" = "Supply the `reference_aois`."
      ))
    }
    if (!all(reference_aois %in% x$layout$aoi)) {
      cli::cli_abort(c(
              "Both `reference_aois` must be present in `x$layout$aoi`.",
        "i" = "Supplied `reference_aois`: {.val {reference_aois}}.",
        "i" = "Supplied `x$layout$aoi`: {.val {x$layout$aoi}}."
      ))
    }
  }

  # ---- Validate grouping variables -------------------------------------------
  if (!is.null(grp_vars)) {
    if (is.null(x$responses)) {
      grp_vars <- NULL
      cli::cli_warn(c(
        "!" = "`grp_vars` specified with `x$responses` missing.",
        "i" = "Setting `grp_vars` to NULL",
        "i" = "If you wish to include grouping variables, provide valid `x$responses`."
      ))
    } else {
      missing_grps <- grp_vars[!grp_vars %in% names(x$responses)]
      if (length(missing_grps > 1L)) {
        grp_vars <- grp_vars[grp_vars %in% names(x$responses)]
        cli::cli_warn(c(
          "",
          "!" = "All specified `grp_vars` must be present in `x$responses`.",
          "i" = "{.val {missing_grps}} {?was/were} specified as `grp_vars` but {?is/are} missing from `x$response`.",
          "i" = "Dropping {.val {missing_grps}} from `grp_vars`.",
          "i" = "Remaining `grp_vars`: {.val {grp_vars}}."
        ))
      }
    }
  }

  # --- Fill-in statistics -----------------------------------------------------
  if (length(stats) < 2L) {
    if (is.null(stats) || stats == "all") {
      stats_display <- if (is.null(stats)) "NULL" else stats
      cli::cli_inform(c(
        "i" = "`stats` set to {.val {stats_display}} \u2192 all available statistics will be computed.",
        "i" = "Computing all of {.val {(.valid_et_stats)}}."
      ))
      stats <- .valid_et_stats
    }
  }

  # --- Grouping structure -----------------------------------------------------
  id_cols  <- names(x$fixations)[endsWith(names(x$fixations), "_id")]
  grp_full <- unique(c(id_cols, trial_vars))

  if (is.null(query_aoi)) {
    query_aoi <- NA_character_
  }
  if (is.null(reference_aois)) {
    reference_aois <- c(NA_character_, NA_character_)
  }

  # --- Annotate and trim ------------------------------------------------------
  annotated <-
    x$fixations |>
    .annotate_fixations(x$layout) |>
    dplyr::filter(
      .data$stime > 0,
      .data$etime < window
    ) |>
    dplyr::arrange(
      dplyr::across(tidyselect::all_of(grp_full)),
      .data$stime
    )

  # --- Revisit counts (per group x AOI) ---------------------------------------
  revisits <-
    annotated |>
    dplyr::mutate(
      aoi = dplyr::if_else(is.na(.data$aoi), "blank", .data$aoi) # To ensure aoi to blank to aoi counts as revisit
    ) |>
    dplyr::group_by(dplyr::across(tidyselect::all_of(grp_full))) |>
    dplyr::mutate(
      visit_id = cumsum(
        .data$aoi != dplyr::lag(.data$aoi, default = dplyr::first(.data$aoi))
      )
    ) |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(c(grp_full, "aoi")))
    ) |>
    dplyr::summarise(
      revisits_count = dplyr::n_distinct(.data$visit_id) - 1L,
      .groups = "drop"
    ) |>
    dplyr::filter(.data$aoi != "blank")

  # --- Switch / transition counts (per group) ---------------------------------
  count_switches <- function(aoi, na.rm = FALSE) {
    if (na.rm) aoi <- aoi[stats::complete.cases(aoi)]
    prev <- dplyr::lag(aoi)
    sum(!is.na(aoi) & !is.na(prev) & aoi != prev)
  }

  count_transitions <- function(aoi, stim1, stim2, na.rm = FALSE) {
    if (na.rm) aoi <- aoi[stats::complete.cases(aoi)]
    prev <- dplyr::lag(aoi)
    trans <- ((aoi %in% stim1 & prev %in% stim2) | (aoi %in% stim2 & prev %in% stim1)) & aoi != prev
    sum(trans, na.rm = TRUE)
  }

  group_stats <-
    annotated |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(grp_full))
    ) |>
    dplyr::summarise(
      switches_direct = count_switches(.data$aoi),
      switches_total = count_switches(.data$aoi, na.rm = TRUE),
      watch_time = max(.data$etime),
      transitions_ref_to_ref = count_transitions(
        .data$aoi,
        reference_aois[1L],
        reference_aois[2L],
        na.rm = TRUE
      ),
      direct_transitions_ref_to_ref = count_transitions(
        .data$aoi,
        reference_aois[1L],
        reference_aois[2L],
        na.rm = FALSE
      ),
      transitions_query_refs = count_transitions(
        .data$aoi,
        query_aoi,
        reference_aois,
        na.rm = TRUE
      ),
      direct_transitions_query_refs = count_transitions(
        .data$aoi,
        query_aoi,
        reference_aois,
        na.rm = FALSE
      ),
      transitions_query_ref1 = count_transitions(
        .data$aoi,
        query_aoi,
        reference_aois[1L],
        na.rm = TRUE
      ),
      direct_transitions_query_ref1 = count_transitions(
        .data$aoi,
        query_aoi,
        reference_aois[1L],
        na.rm = FALSE
      ),
      transitions_query_ref2 = count_transitions(
        .data$aoi,
        query_aoi,
        reference_aois[2L],
        na.rm = TRUE
      ),
      direct_transitions_query_ref2 = count_transitions(
        .data$aoi,
        query_aoi,
        reference_aois[2L],
        na.rm = FALSE
      ),
      .groups = "drop"
    )

  # --- Reference-specific statistics ------------------------------------------
  ref_stats <-
    annotated |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(grp_full))
    ) |>
    dplyr::summarise(
      first_reference_fixation_start = {
        ref_times <- .data$stime[.data$aoi %in% reference_aois]
        if (length(ref_times) == 0L) {
          NA_real_
        } else {
          min(ref_times)
        }
      },
      first_fixated_reference = {
        if (is.na(.data$first_reference_fixation_start)) {
          NA_character_
        } else {
          .data$aoi[.data$stime == .data$first_reference_fixation_start]
        }
      },
      last_reference_fixation_end = {
        ref_times <- .data$etime[.data$aoi %in% reference_aois]
        if (length(ref_times) == 0L) {
          NA_real_
        } else {
          max(ref_times)
        }
      },
      last_fixated_reference = {
        if (is.na(.data$last_reference_fixation_end)) {
          NA_character_
        } else {
          .data$aoi[.data$etime == .data$last_reference_fixation_end]
        }
      },
      .groups = "drop"
    )

  # --- Per-AOI dwell statistics (per group x AOI) -----------------------------
  aoi_stats <-
    annotated |>
    dplyr::filter(!is.na(.data$aoi)) |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(c(grp_full, "aoi")))
    ) |>
    dplyr::summarise(
      fixation_count = dplyr::n(),
      dwell_time_total = sum(.data$dur),
      dwell_time_mean = mean(.data$dur),
      dwell_time_median = stats::median(.data$dur),
      dwell_time_sd = stats::sd(.data$dur),
      first_fixation_start = {
        if (length(.data$stime) == 0L) {
          NA_real_
        } else {
          max(0, min(.data$stime))
        }
      },
      last_fixation_end = max(.data$etime),
      .groups = "drop"
    ) |>
    tidyr::complete(!!!rlang::syms(c(grp_full, "aoi"))) |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(grp_full))
    ) |>
    dplyr::mutate(
      first_fixated_aoi = {
        if (all(is.na(.data$first_fixation_start))) {
          NA_character_
        } else {
          dplyr::first(.data$aoi[which.min(.data$first_fixation_start)])
        }
      },
      last_fixated_aoi = {
        if (all(is.na(.data$last_fixation_end))) {
          NA_character_
        } else {
          dplyr::last(.data$aoi[which.max(.data$last_fixation_end)])
        }
      }
    ) |>
    dplyr::ungroup()

  # --- Assemble structural zeros and join -------------------------------------
  combined <-
    aoi_stats |>
    dplyr::left_join(revisits, by = c(grp_full, "aoi")) |>
    dplyr::left_join(group_stats, by = grp_full) |>
    dplyr::left_join(ref_stats, by = grp_full) |>
    dplyr::mutate(
      dplyr::across(
        tidyselect::any_of(names(.et_measure_fills)),
        \(v) dplyr::coalesce(v, .et_measure_fills[[dplyr::cur_column()]])
      )
    )

  # --- Optionally add responses -----------------------------------------------
  if (!is.null(x$responses)) {
    join_by_id <- intersect(id_cols, names(x$responses))
    responses <- x$responses |>
      dplyr::select(tidyselect::all_of(c(join_by_id, trial_vars, grp_vars)))
    combined <- dplyr::left_join(
      combined,
      responses,
      by = c(join_by_id, trial_vars),
      relationship = "many-to-one"
    )
  }

  # --- Select requested statistics and apply window suffix --------------------
  output <-
    combined |>
    dplyr::select(
      tidyselect::all_of(grp_full),
      tidyselect::all_of(grp_vars),
      tidyselect::contains("aoi"),
      tidyselect::all_of(stats)
    ) |>
    dplyr::rename_with(
      .fn = \(nm) {
        suffix <- if (is.infinite(window)) "" else glue::glue("_{window}")
        glue::glue("{nm}{suffix}")
      },
      .cols = tidyselect::all_of(stats)
    )

  attr(output, "id_cols")    <- id_cols
  attr(output, "trial_cols") <- trial_vars
  attr(output, "grp_vars")   <- grp_vars
  output
}
