# Valid types of derived data
.valid_process_types <- c(
  "indexes",
  "cascade"
)

# Valid eye-tracking statistics
.valid_et_stats <- c(
  "fix_count",
  "dwell_total",
  "dwell_mean",
  "dwell_median",
  "dwell_sd",
  "switches_total",
  "revisits_count",
  "transitions_ref_to_ref",
  "transitions_query_refs",
  "transitions_query_ref1",
  "transitions_query_ref2",
  "first_fix_start",
  "first_reference_fix_start",
  "last_fix_end",
  "watch_time"
)

# Transition statistics that require `query_aoi` and `reference_aois`
.transition_et_stats <- c(
  "transitions_ref_to_ref",
  "transitions_query_refs",
  "transitions_query_ref1",
  "transitions_query_ref2"
)

# Structural fills for eye tracking statistics
.et_index_fills <- list(
  fix_count              = 0L,
  revisits_count         = 0L,
  switches_total         = 0L,
  transitions_ref_to_ref = 0L,
  transitions_query_refs = 0L,
  transitions_query_ref1 = 0L,
  transitions_query_ref2 = 0L,
  dwell_total            = 0
)


#' Annotate fixation data with AOIs
#'
#' Given an AOI `layout`, add for each recorded fixation in `data` the `aoi`
#' that was fixated. Fixations that fall outside every AOI are preserved with
#' `NA` in the `aoi` column.
#'
#' @param data Fixation data, following the naming conventions of
#'   [import_eyelink_data()].
#' @param layout Data.frame of AOI geometry containing at least the boundary
#'   columns `aoi`, `xleft`, `xright`, `ybottom`, and `ytop`.
#'
#' @returns `data` with an added `aoi` column.
#'
#' @noRd
.annotate_fixations <- function(data, layout) {
  original_cols <- colnames(data)

  data_aoi_fixated <-
    data |>
    dplyr::cross_join(layout) |>
    dplyr::filter(
      .data$axp >= .data$xleft, .data$axp <= .data$xright,
      .data$ayp >= .data$ybottom, .data$ayp <= .data$ytop
    ) |>
    dplyr::select(
      tidyselect::all_of(c(original_cols, "aoi"))
    )

  result <- dplyr::left_join(
    data,
    data_aoi_fixated,
    by = original_cols
  )

  # Guard against overlapping AOIs
  if (nrow(result) > nrow(data)) {
    multi_aoi <-
      data_aoi_fixated |>
      dplyr::group_by(
        dplyr::across(tidyselect::all_of(original_cols))
      ) |>
      dplyr::summarise(n_aoi = dplyr::n(), .groups = "drop") |>
      dplyr::filter(.data$n_aoi > 1L)

    offending <- which(
      do.call(paste, data[original_cols]) %in%
        do.call(paste, multi_aoi[original_cols])
    )

    cli::cli_abort(c(
            "`layout` contains overlapping AOIs.",
      "x" = "{length(offending)} fixation row{?s} matched multiple AOIs.",
      "i" = "Affected fixation row{?s}: {.val {offending}}."
    ))
  }

  result
}


#' Compute trial-level grouped eye-tracking indexes
#'
#' Using export from EyeLink eye-tracking experiment in Experimental Builder,
#' such as data generated by \code{import_eyelink_group}, the function extracts
#' selected eye-tracking statistics per user-specified groups of observations.
#'
#' @param x An `mpr_eyelink_eyetracking` object.
#' @param grp_vars Character vector of grouping variable names, or `NULL`.
#' @param stats Character vector of statistics to compute; validated against
#'   `.valid_et_stats`.
#' @param window Numeric. Upper bound on fixation `etime`; `Inf` keeps all.
#' @param query_aoi Character(1). Label of the query AOI, or `NULL`. Required
#'   only for `transitions_*` statistics.
#' @param reference_aois Character(2) labels of the reference AOIs, or `NULL`.
#'   Required only for `transitions_*` statistics.
#'
#' @returns A data.frame with one row per identifier x `grp_vars` x `aoi`
#'   combination and one column per requested statistic.
#'
#' @noRd
.process_et_indexes <- function(
    x,
    grp_vars,
    stats,
    window,
    query_aoi,
    reference_aois
) {
  # --- Validate requested statistics ------------------------------------------
  unknown_stats <- setdiff(stats, .valid_et_stats)
  if (length(unknown_stats) > 0L) {
    cli::cli_abort(c(
            "Unknown statistic{?s} requested in `stats`: {.val {unknown_stats}}.",
      "i" = "Valid statistics are: {.val {get(.valid_et_stats)}}."
    ))
  }

  requested_transitions <- intersect(stats, .transition_et_stats)
  if (length(requested_transitions) > 0L &&
      (is.null(query_aoi) || is.null(reference_aois))) {
    cli::cli_abort(c(
            "Transition statistics require both `query_aoi` and `reference_aois`.",
      "x" = "Requested transition stat{?s}: {.val {requested_transitions}}.",
      "i" = "Supply the `query_aoi` and both `reference_aois`."
    ))
  }

  if ("first_reference_fix_start" %in% stats && is.null(reference_aois)) {
    cli::cli_warn(c(
      "!" = "`first_reference_fix_start` was requested without `reference_aois`; values are `NA`."
    ))
  }

  # --- Grouping structure -----------------------------------------------------
  id_cols  <- names(x$fixations)[endsWith(names(x$fixations), "_id")]
  grp_full <- unique(c(id_cols, grp_vars))

  if (is.null(query_aoi)) {
    query_aoi <- NA_character_
  }
  if (is.null(reference_aois)) {
    reference_aois <- c(NA_character_, NA_character_)
  }

  # --- Annotate, trim and (optionally) join responses -------------------------
  annotated <-
    x$fixations |>
    .annotate_fixations(x$layout) |>
    dplyr::filter(
      .data$stime > 0,
      .data$etime < window
    )

  if (!is.null(x$responses)) {
    join_by_id <- intersect(id_cols, names(x$responses))
    annotated <- dplyr::left_join(
      annotated,
      x$responses,
      by = join_by_id,
      relationship = "many-to-one"
    )
  }

  annotated <-
    annotated |>
    dplyr::arrange(
      dplyr::across(tidyselect::all_of(grp_full)),
      .data$stime
    )

  # --- Revisit counts (per group x AOI) ---------------------------------------
  revisits <-
    annotated |>
    dplyr::mutate(
      aoi = dplyr::if_else(is.na(.data$aoi), "blank", .data$aoi) # To ensure aoi to blank to aoi counts as revisit
    ) |>
    dplyr::group_by(dplyr::across(tidyselect::all_of(grp_full))) |>
    dplyr::mutate(
      visit_id = cumsum(
        .data$aoi != dplyr::lag(.data$aoi, default = dplyr::first(.data$aoi))
      )
    ) |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(c(grp_full, "aoi")))
    ) |>
    dplyr::summarise(
      revisits_count = dplyr::n_distinct(.data$visit_id) - 1L,
      .groups = "drop"
    ) |>
    dplyr::filter(.data$aoi != "blank")

  # --- Switch / transition counts (per group) ---------------------------------
  count_switches <- function(aoi) {
    prev <- dplyr::lag(aoi)
    sum(!is.na(aoi) & !is.na(prev) & aoi != prev)
  }

  group_stats <-
    annotated |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(grp_full))
    ) |>
    dplyr::summarise(
      switches_total = count_switches(.data$aoi),
      watch_time = max(.data$etime),
      first_reference_fix_start = {
        ref_times <- .data$stime[.data$aoi %in% reference_aois]
        if (length(ref_times) == 0L) {
          NA_real_
        } else {
          min(ref_times)
        }
      },
      transitions_ref_to_ref = {
        prev <- dplyr::lag(.data$aoi)
        sum(
          .data$aoi %in% reference_aois &
            prev %in% reference_aois &
            .data$aoi != prev,
          na.rm = TRUE
        )
      },
      transitions_query_refs = {
        prev <- dplyr::lag(.data$aoi)
        sum(
          (.data$aoi == query_aoi & prev %in% reference_aois) |
            (.data$aoi %in% reference_aois & prev == query_aoi),
          na.rm = TRUE
        )
      },
      transitions_query_ref1 = {
        prev <- dplyr::lag(.data$aoi)
        sum(
          (.data$aoi == query_aoi & prev == reference_aois[1L]) |
            (.data$aoi == reference_aois[1L] & prev == query_aoi),
          na.rm = TRUE
        )
      },
      transitions_query_ref2 = {
        prev <- dplyr::lag(.data$aoi)
        sum(
          (.data$aoi == query_aoi & prev == reference_aois[2L]) |
            (.data$aoi == reference_aois[2L] & prev == query_aoi),
          na.rm = TRUE
        )
      },
      .groups = "drop"
    )

  # --- Per-AOI dwell statistics (per group x AOI) -----------------------------
  aoi_stats <-
    annotated |>
    dplyr::filter(!is.na(.data$aoi)) |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(c(grp_full, "aoi")))
    ) |>
    dplyr::summarise(
      fix_count = dplyr::n(),
      dwell_total = sum(.data$dur),
      dwell_mean = mean(.data$dur),
      dwell_median = stats::median(.data$dur),
      dwell_sd = stats::sd(.data$dur),
      first_fix_start = {
        if (length(.data$stime) == 0L) {
          NA_real_
        } else {
          max(0, min(.data$stime))
        }
      },
      last_fix_end = max(.data$etime),
      .groups = "drop"
    )

  # --- Assemble structural zeros and join -------------------------------------
  combined <-
    aoi_stats |>
    tidyr::complete(!!!rlang::syms(c(grp_full, "aoi"))) |>
    dplyr::left_join(revisits, by = c(grp_full, "aoi")) |>
    dplyr::left_join(group_stats, by = grp_full) |>
    dplyr::mutate(
      dplyr::across(
        tidyselect::any_of(names(.et_index_fills)),
        \(v) dplyr::coalesce(v, .et_index_fills[[dplyr::cur_column()]])
      )
    )

  # --- Select requested statistics and apply window suffix --------------------
  combined |>
    dplyr::select(
      tidyselect::all_of(grp_full),
      tidyselect::all_of("aoi"),
      tidyselect::all_of(stats)
    ) |>
    dplyr::rename_with(
      .fn = \(nm) {
        suffix <- if (is.infinite(window)) "" else glue::glue("_{window}")
        glue::glue("{nm}{suffix}")
      },
      .cols = tidyselect::all_of(stats)
    )
}


#' Compute grouped gaze-cascade dwell proportions
#'
#' Adapts the gaze-cascade logic to the `mpr_eyelink_eyetracking` structure.
#' Time is expressed relative to the response and runs backwards over `n_bins`
#' equal-width bins spanning `[-window, 0]`. Reference-AOI fixations are
#' classified as `"chosen"` or `"unchosen"` against the per-trial choice, and
#' per-bin dwell overlap is aggregated to cluster-level average proportions.
#'
#' @param x An `mpr_eyelink_eyetracking` object; `x$responses` must not be
#'   `NULL`.
#' @param trial_vars Character vector of variables denoting a unique trial
#'   identification. These variables need to be present in bot `x$fixations`
#'   and `x$responses`
#' @param grp_vars Character vector of grouping variable names, or `NULL`.
#' @param n_bins Integer(1). Number of equal-width time bins.
#' @param window Numeric(1). Positive, finite span of the cascade window.
#' @param response_time_col Character(1). Response time column in `x$responses`.
#' @param chosen_aoi_col Character(1). Chosen AOI column in `x$responses`.
#'
#' @returns A data.frame with one row per identifier x `grp_vars` x `bin`,
#'   carrying `average_prop_chosen` and `n_trials`. Carries `window`,
#'   `n_bins`, and `grp_vars` as attributes so that
#'   [plot.mpr_gaze_cascade()] can reconstruct the time axis and grouping
#'   without the user re-supplying them.
#'
#' @noRd
.process_gaze_cascade <- function(
    x,
    trial_vars,
    grp_vars,
    n_bins,
    window,
    response_time_col,
    chosen_aoi_col
) {
  # --- Preconditions ----------------------------------------------------------
  if (is.null(x$responses)) {
    cli::cli_abort(c(
            "Gaze-cascade analysis requires participant responses.",
      "x" = "`x$responses` is `NULL`.",
      "i" = "Provide responses with `{response_time_col}` and `{chosen_aoi_col}` columns."
    ))
  }

  if (!is.finite(window) || window <= 0) {
    cli::cli_abort(c(
            "`window` must be a finite, positive number for gaze-cascade analysis.",
      "x" = "Received {.val {window}}."
    ))
  }

  response_missing_trial_cols <- setdiff(trial_vars, colnames(x$responses))
  if (length(response_missing_trial_cols) > 0L) {
    cli::cli_abort(c(
            "`trial_cols` must be present in `x$responses`.",
      "x" = "The following column{?} {?is/are} missing: {.var {response_missing_trial_cols}}."
    ))
  }

  fixations_missing_trial_cols <- setdiff(trial_vars, colnames(x$fixations))
  if (length(fixations_missing_trial_cols) > 0L) {
    cli::cli_abort(c(
            "`trial_cols` must be present in `x$fixations`.",
      "`trial_cols` must be present in `x$fixations`.",
      "x" = "The following column{?} {?is/are} missing: {.var {fixations_missing_trial_cols}}."
    ))
  }

  # --- Time unit detection (ms -> s) ------------------------------------------
  if (window > 30) {
    cli::cli_inform(c(
      "!" = "`window = {window}` looks like milliseconds (threshold: > 30).",
      "i" = "Assuming ms: converting `stime`, `etime`, `{response_time_col}`, and `window` to seconds.",
      "i" = "Pass `window` in seconds (e.g., {.val {window / 1000}}) to silence this message."
    ))
    x$fixations <- dplyr::mutate(
      x$fixations,
      stime = .data$stime / 1e3,
      etime = .data$etime / 1e3
    )
    x$responses <- dplyr::mutate(
      x$responses,
      dplyr::across(tidyselect::all_of(response_time_col), \(v) v / 1e3)
    )
    window <- window / 1e3
  }

  missing_resp_cols <- setdiff(
    c(response_time_col, chosen_aoi_col),
    names(x$responses)
  )
  if (length(missing_resp_cols) > 0L) {
    cli::cli_abort(c(
      "x" = "`responses` is missing required column{?s}: {.val {missing_resp_cols}}."
    ))
  }

  # --- Grouping structure -----------------------------------------------------
  id_cols    <- names(x$fixations)[endsWith(names(x$fixations), "_id")]
  join_by_id <- intersect(id_cols, names(x$responses))
  grp_full   <- unique(c(id_cols, grp_vars))

  resp <-
    x$responses |>
    dplyr::mutate(
      response_time = .data[[response_time_col]],
      chosen_aoi    = .data[[chosen_aoi_col]]
    )

  reference_aois <- unique(stats::na.omit(resp[["chosen_aoi"]]))

  # --- Annotate fixations and attach the per-trial response -------------------
  annotated <-
    x$fixations |>
    .annotate_fixations(x$layout) |>
    dplyr::left_join(
      resp,
      by = c(join_by_id, trial_vars),
      relationship = "many-to-one"
    )

  # --- Classify reference fixations and rebase time on the response -----------
  classified <-
    annotated |>
    dplyr::filter(
      .data$aoi %in% reference_aois,
      !is.na(.data$chosen_aoi)
    ) |>
    dplyr::mutate(
      class = factor(
        dplyr::if_else(.data$aoi == .data$chosen_aoi, "chosen", "unchosen"),
        levels = c("chosen", "unchosen")
      ),
      stime_resp = .data$stime - .data$response_time,
      etime_resp = .data$etime - .data$response_time
    )

  # --- Build equal-width bins over [-window, 0] -------------------------------
  breaks <- seq(-window, 0, length.out = n_bins + 1L)
  bins <- tibble::tibble(
    bin   = seq_len(n_bins),
    lower = breaks[-length(breaks)],
    upper = breaks[-1L]
  )

  # --- Per-trial dwell overlap and chosen proportion --------------------------
  trial_level <-
    classified |>
    dplyr::cross_join(bins) |>
    dplyr::mutate(
      overlap = pmax(
        0,
        pmin(.data$etime_resp, .data$upper) -
          pmax(.data$stime_resp, .data$lower)
      )
    ) |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(c(grp_full, trial_vars, "bin", "class")))
    ) |>
    dplyr::summarise(
      dwell = sum(.data$overlap),
      .groups = "drop"
    ) |>
    tidyr::pivot_wider(
      names_from   = "class",
      values_from  = "dwell",
      values_fill  = 0,
      names_expand = TRUE,
      names_prefix = "dwell_"
    ) |>
    dplyr::mutate(
      total_dwell = .data$dwell_chosen + .data$dwell_unchosen,
      prop_chosen = dplyr::if_else(
        .data$total_dwell > 0,
        .data$dwell_chosen / .data$total_dwell,
        NA_real_
      )
    )

  # --- Cluster-level average cascade ------------------------------------------
  output <-
    trial_level |>
    dplyr::group_by(
      dplyr::across(tidyselect::all_of(c(grp_full, "bin")))
    ) |>
    dplyr::summarise(
      average_prop_chosen = {
        if (all(is.na(.data$prop_chosen))) {
          NA_real_
        } else {
          mean(.data$prop_chosen, na.rm = TRUE)
        }
      },
      n_trials = sum(!is.na(.data$prop_chosen)),
      .groups = "drop"
    )

  # Stamp window/n_bins/grp_vars so that plot.mpr_gaze_cascade can
  # reconstruct the time axis and grouping without requiring the user to
  # re-supply these arguments.
  attr(output, "window")   <- window
  attr(output, "n_bins")   <- n_bins
  attr(output, "grp_vars") <- grp_vars
  output
}


#' @describeIn process Method for `mpr_eyelink_eyetracking` objects.
#' @export
process.mpr_eyelink_eyetracking <- function(
    x,
    type              = c("indexes", "cascade"),
    trial_vars        = "trial_index",
    grp_vars          = NULL,
    stats             = c("fix_count", "dwell_total"),
    window            = Inf,
    query_aoi         = NULL,
    reference_aois    = NULL,
    n_bins            = 100L,
    response_time_col = "response_time",
    chosen_aoi_col    = "chosen_aoi",
    ...
) {
  # --- Validate `type` --------------------------------------------------------
  type <- match.arg(type)
  if (missing(type)) {
    cli::cli_abort(c(
      "`type` is required and has no default.",
      "i" = "Choose one of {.val {get(.valid_process_types)}}."
    ))
  }
  if (!rlang::is_string(type) || !type %in% .valid_process_types) {
    cli::cli_abort(c(
      "`type` must be one of {.val {get(.valid_process_types)}}.",
      "x" = "Received {.val {type}}."
    ))
  }

  # --- Warn on type-irrelevant arguments supplied with non-default values -----
  if (type == "indexes") {
    irrelevant <- c(
      if (!identical(n_bins, 100L)) "n_bins",
      if (!identical(response_time_col, "response_time")) "response_time_col",
      if (!identical(chosen_aoi_col, "chosen_aoi")) "chosen_aoi_col"
    )
  } else if (type == "cascade") {
    irrelevant <- c(
      if (!identical(stats, c("fix_count", "dwell_total"))) "stats",
      if (!is.null(query_aoi)) "query_aoi",
      if (!is.null(reference_aois)) "reference_aois"
    )
  }
  if (length(irrelevant) > 0L) {
    cli::cli_warn(c(
      "!" = "Argument{?s} {.arg {irrelevant}} {?is/are} ignored for `type = {.val {type}}`."
    ))
  }

  # --- Dispatch to the appropriate worker -------------------------------------
  x$derivatives <- switch(
    type,
    indexes = .process_et_indexes(
      x, grp_vars, stats, window, query_aoi, reference_aois
    ),
    cascade = .process_gaze_cascade(
      x, trial_vars, grp_vars, n_bins, window, response_time_col, chosen_aoi_col
    )
  )

  # --- Prepend the result class -----------------------------------------------
  result_class <- switch(
    type,
    indexes = "mpr_et_indexes",
    cascade = "mpr_gaze_cascade"
  )
  class(x) <- c(
    result_class,
    setdiff(class(x), c("mpr_et_indexes", "mpr_gaze_cascade"))
  )

  invisible(x)
}
